// Excel (.xlsx) export (docs/DESIGN.md §12). One row per message, grouped by
// thread so structure survives; a Manifest sheet carries chain-of-custody
// details. Read-only artifact (produced fresh each export).
import ExcelJS from 'exceljs';
import { ExportMessage, ExportMeta } from './html';

const strip = (html?: string | null) =>
  (html || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

export async function renderConversationXlsx(messages: ExportMessage[], meta: ExportMeta): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Cortex-PA';

  // Manifest sheet.
  const man = wb.addWorksheet('Manifest');
  man.columns = [{ header: 'Field', key: 'k', width: 22 }, { header: 'Value', key: 'v', width: 80 }];
  man.getRow(1).font = { bold: true };
  [
    ['Case number', meta.caseNumber], ['Project codename', meta.projectCodename],
    ['Conversation', meta.conversationLabel], ['Scope', meta.scope],
    ['Generated by', meta.generatedByName], ['Generated at (UTC)', meta.generatedAtIso],
    ['Message count', String(messages.length)], ['Note', 'Read-only evidence export'],
  ].forEach(([k, v]) => man.addRow({ k, v }));

  // Messages sheet, ordered roots-then-replies to preserve threading.
  const ws = wb.addWorksheet('Messages');
  ws.columns = [
    { header: 'Thread', key: 'thread', width: 28 },
    { header: 'Type', key: 'type', width: 10 },
    { header: 'Sender', key: 'sender', width: 24 },
    { header: 'Timestamp', key: 'ts', width: 22 },
    { header: 'Message', key: 'msg', width: 70 },
    { header: 'Reactions', key: 'rx', width: 22 },
    { header: 'Status', key: 'status', width: 12 },
    { header: 'SHA-256', key: 'hash', width: 66 },
  ];
  ws.getRow(1).font = { bold: true };
  ws.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEEF1F6' } };

  const byParent = new Map<string, ExportMessage[]>();
  const roots: ExportMessage[] = [];
  for (const m of messages) {
    if (m.reply_to_id) { const a = byParent.get(m.reply_to_id) || []; a.push(m); byParent.set(m.reply_to_id, a); }
    else roots.push(m);
  }
  const rxText = (m: ExportMessage) => {
    if (!m.reactions?.length) return '';
    const c: Record<string, number> = {};
    for (const r of m.reactions) c[r.reaction_type] = (c[r.reaction_type] || 0) + 1;
    return Object.entries(c).map(([t, n]) => `${t} ${n}`).join(', ');
  };
  const addRow = (m: ExportMessage, isReply: boolean) => {
    const row = ws.addRow({
      thread: m.reply_to_id || m.message_id,
      type: isReply ? 'reply' : 'root',
      sender: m.from_name || 'Unknown',
      ts: m.created_at || '',
      msg: m.deleted_at ? 'This message was deleted.' : strip(m.body_html),
      rx: rxText(m),
      status: m.deleted_at ? 'Deleted' : m.last_edited_at ? 'Edited' : '',
      hash: m.content_sha256 || '',
    });
    if (isReply) row.outlineLevel = 1;
  };
  for (const r of roots) { addRow(r, false); for (const rep of (byParent.get(r.message_id) || [])) addRow(rep, true); }

  const buf = await wb.xlsx.writeBuffer();
  return Buffer.from(buf);
}
