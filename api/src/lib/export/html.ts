// Self-contained HTML export (docs/DESIGN.md §12). Preserves the Teams
// threaded layout with names, timestamps, avatars, reactions, and status.
// Output is a single file with inline CSS and base64 avatars — no external
// calls — plus a chain-of-custody manifest header. Read-only by nature.

export interface ExportMessage {
  message_id: string;
  reply_to_id?: string | null;
  from_name?: string | null;
  avatar?: string | null;      // data URI
  body_html?: string | null;   // already sanitized
  created_at?: string | null;
  last_edited_at?: string | null;
  deleted_at?: string | null;
  reactions?: { reaction_type: string; actor_name?: string | null }[];
  content_sha256?: string | null;
}

export interface ExportMeta {
  caseNumber: string;
  projectCodename: string;
  conversationLabel: string;
  generatedByName: string;
  generatedAtIso: string;
  scope: string;               // "All" | "Range …" | "Selected (n)"
}

const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function reactionChips(m: ExportMessage): string {
  if (!m.reactions?.length) return '';
  const counts: Record<string, number> = {};
  for (const r of m.reactions) counts[r.reaction_type] = (counts[r.reaction_type] || 0) + 1;
  return `<div class="reactions">${Object.entries(counts)
    .map(([t, n]) => `<span class="reaction">${esc(t)} ${n}</span>`).join('')}</div>`;
}

function statusChip(m: ExportMessage): string {
  if (m.deleted_at) return `<span class="status deleted">Deleted ${esc(m.deleted_at)}</span>`;
  if (m.last_edited_at) return `<span class="status edited">Edited ${esc(m.last_edited_at)}</span>`;
  return '';
}

function bubble(m: ExportMessage, isReply: boolean): string {
  const av = m.avatar
    ? `<img class="avatar" src="${m.avatar}" alt="">`
    : `<div class="avatar initials">${esc((m.from_name || '?').slice(0, 1))}</div>`;
  const body = m.deleted_at
    ? '<em class="tomb">This message was deleted.</em>'
    : (m.body_html || '');
  return `
  <div class="msg ${isReply ? 'reply' : 'root'}">
    ${av}
    <div class="content">
      <div class="meta"><span class="name">${esc(m.from_name || 'Unknown')}</span>
        <span class="time">${esc(m.created_at || '')}</span> ${statusChip(m)}</div>
      <div class="body">${body}</div>
      ${reactionChips(m)}
      <div class="hash">${m.content_sha256 ? 'sha256:' + m.content_sha256 : ''}</div>
    </div>
  </div>`;
}

export function renderConversationHtml(messages: ExportMessage[], meta: ExportMeta): string {
  // Reconstruct threads: roots in chronological order, replies nested under parent.
  const byParent = new Map<string, ExportMessage[]>();
  const roots: ExportMessage[] = [];
  for (const m of messages) {
    if (m.reply_to_id) {
      const arr = byParent.get(m.reply_to_id) || [];
      arr.push(m); byParent.set(m.reply_to_id, arr);
    } else roots.push(m);
  }
  const body = roots.map(r => {
    const replies = (byParent.get(r.message_id) || []).map(x => bubble(x, true)).join('');
    return bubble(r, false) + (replies ? `<div class="thread">${replies}</div>` : '');
  }).join('');

  return `<!doctype html><html><head><meta charset="utf-8">
<title>${esc(meta.projectCodename)} — ${esc(meta.conversationLabel)}</title>
<style>
  body{font-family:Segoe UI,Arial,sans-serif;color:#1b1b1b;background:#faf9f8;margin:0}
  .manifest{background:#eef1f6;border-bottom:2px solid #c7d0e0;padding:16px 24px;font-size:13px}
  .manifest b{color:#33415c}
  .wrap{max-width:920px;margin:0 auto;padding:24px}
  .msg{display:flex;gap:12px;padding:10px 0}
  .msg.reply{margin-left:44px}
  .thread{border-left:2px solid #e1dfdd;margin-left:20px}
  .avatar{width:32px;height:32px;border-radius:50%;object-fit:cover;flex:0 0 32px}
  .avatar.initials{background:#5b5fc7;color:#fff;display:flex;align-items:center;justify-content:center;font-weight:600}
  .meta{font-size:12px;color:#616161}
  .name{font-weight:600;color:#242424}
  .status{margin-left:8px;font-size:11px;padding:1px 6px;border-radius:8px}
  .status.edited{background:#fff4ce}
  .status.deleted{background:#fde7e9;color:#a4262c}
  .body{margin-top:2px}
  .tomb{color:#a19f9d}
  .reactions{margin-top:4px}
  .reaction{background:#eef2fb;border:1px solid #d6def0;border-radius:12px;padding:1px 8px;font-size:12px;margin-right:4px}
  .hash{font-size:10px;color:#b3b0ad;margin-top:2px;font-family:monospace}
</style></head><body>
<div class="manifest">
  <div><b>Case:</b> ${esc(meta.caseNumber)} &nbsp; <b>Project:</b> ${esc(meta.projectCodename)}</div>
  <div><b>Conversation:</b> ${esc(meta.conversationLabel)} &nbsp; <b>Scope:</b> ${esc(meta.scope)}</div>
  <div><b>Generated by:</b> ${esc(meta.generatedByName)} &nbsp; <b>At:</b> ${esc(meta.generatedAtIso)}</div>
  <div><b>Messages:</b> ${messages.length} — read-only evidence export; hashes shown per message for chain of custody.</div>
</div>
<div class="wrap">${body}</div>
</body></html>`;
}
