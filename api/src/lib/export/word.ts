// Word (.docx) export (docs/DESIGN.md §12). Threaded layout: root posts with
// indented replies, sender + timestamp, reactions, status, per-message hash,
// and a chain-of-custody manifest header. Read-only artifact.
import {
  Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle,
} from 'docx';
import { ExportMessage, ExportMeta } from './html';

const strip = (html?: string | null) =>
  (html || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

function messageParagraphs(m: ExportMessage, isReply: boolean): Paragraph[] {
  const indent = isReply ? { left: 720 } : undefined;
  const status = m.deleted_at ? '  [Deleted]' : m.last_edited_at ? '  [Edited]' : '';
  const header = new Paragraph({
    indent,
    spacing: { before: 120 },
    children: [
      new TextRun({ text: m.from_name || 'Unknown', bold: true }),
      new TextRun({ text: `   ${m.created_at || ''}${status}`, size: 16, color: '808080' }),
    ],
  });
  const bodyText = m.deleted_at ? 'This message was deleted.' : strip(m.body_html);
  const body = new Paragraph({ indent, children: [new TextRun({ text: bodyText, italics: !!m.deleted_at })] });
  const out = [header, body];
  if (m.reactions?.length) {
    const counts: Record<string, number> = {};
    for (const r of m.reactions) counts[r.reaction_type] = (counts[r.reaction_type] || 0) + 1;
    out.push(new Paragraph({ indent, children: [new TextRun({
      text: 'Reactions: ' + Object.entries(counts).map(([t, n]) => `${t} ${n}`).join(', '),
      size: 16, color: '5b5fc7' })] }));
  }
  if (m.content_sha256) {
    out.push(new Paragraph({ indent, children: [new TextRun({ text: `sha256:${m.content_sha256}`, size: 12, color: 'b3b0ad' })] }));
  }
  return out;
}

export async function renderConversationDocx(messages: ExportMessage[], meta: ExportMeta): Promise<Buffer> {
  const byParent = new Map<string, ExportMessage[]>();
  const roots: ExportMessage[] = [];
  for (const m of messages) {
    if (m.reply_to_id) { const a = byParent.get(m.reply_to_id) || []; a.push(m); byParent.set(m.reply_to_id, a); }
    else roots.push(m);
  }

  const children: Paragraph[] = [
    new Paragraph({ text: `${meta.projectCodename} — ${meta.conversationLabel}`, heading: HeadingLevel.HEADING_1 }),
    new Paragraph({ children: [new TextRun({ text:
      `Case ${meta.caseNumber} · Scope ${meta.scope} · Generated by ${meta.generatedByName} at ${meta.generatedAtIso} · ${messages.length} messages`,
      size: 18, color: '616161' })],
      border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: 'c7d0e0', space: 4 } } }),
    new Paragraph({ text: '' }),
  ];
  for (const r of roots) {
    children.push(...messageParagraphs(r, false));
    for (const rep of (byParent.get(r.message_id) || [])) children.push(...messageParagraphs(rep, true));
  }
  children.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 240 },
    children: [new TextRun({ text: 'Read-only evidence export — Cortex-PA', size: 14, color: 'b3b0ad' })] }));

  const doc = new Document({ sections: [{ children }] });
  return Packer.toBuffer(doc);
}
